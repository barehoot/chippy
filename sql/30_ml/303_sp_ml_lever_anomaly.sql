-- SR-028 (stretch) · L7 ML.AD_LEVERS: ANOMALY_DETECTION on weekly distribution share (ML.AD_LEVERS) and price
-- index (ML.AD_LEVERS_PRICE) for the run's early-warning brands. Trained on every week before the latest; only
-- the latest week is scored. A DIST_DROP is confirmed when the latest week falls below the lower bound, a
-- PRICE_RISE when it rises above the upper bound. Verdicts are kept in ML.AD_LEVERS_RESULT for T-EW-02.
-- Non-critical, cost-capped step (run_week step 11, "EW_ML").
USE ROLE SR_DEV;

CREATE TABLE IF NOT EXISTS SR_DB.ML.AD_LEVERS_RESULT (
  RUN_ID      VARCHAR(36) NOT NULL,
  MARKET_ID   VARCHAR     NOT NULL,
  BRAND       VARCHAR     NOT NULL,
  SIGNAL      VARCHAR(16) NOT NULL,   -- DIST_DROP | PRICE_RISE
  TS          TIMESTAMP_NTZ,
  Y           FLOAT,
  LOWER_BOUND FLOAT,
  UPPER_BOUND FLOAT,
  FLAGGED     BOOLEAN     NOT NULL
);

CREATE OR REPLACE PROCEDURE SR_DB.APP.SP_ML_LEVER_ANOMALY(P_RUN_ID VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  n   NUMBER DEFAULT 0;
  n_s NUMBER DEFAULT 0;
BEGIN
  EXECUTE IMMEDIATE 'ALTER SESSION SET QUERY_TAG = ''SR|run=' || P_RUN_ID || '|step=EW_ML''';
  DELETE FROM SR_DB.ML.AD_LEVERS_RESULT WHERE RUN_ID = :P_RUN_ID;
  UPDATE SR_DB.APP.EARLY_WARNING SET ML_CONFIRMED = FALSE WHERE RUN_ID = :P_RUN_ID;

  CREATE OR REPLACE TEMPORARY TABLE SR_DB.ML.TMP_LEV_SERIES AS
  SELECT ARRAY_CONSTRUCT(s.MARKET_ID, s.BRAND)::VARIANT AS SERIES, s.WEEK_END_DATE::TIMESTAMP_NTZ AS TS,
         s.DIST_SHARE::FLOAT AS Y_DIST, s.PRICE_INDEX::FLOAT AS Y_PRICE
  FROM SR_DB.CORE.DT_SHARE_WEEK s
  WHERE (s.MARKET_ID, s.BRAND) IN (SELECT MARKET_ID, BRAND FROM SR_DB.APP.EARLY_WARNING WHERE RUN_ID = :P_RUN_ID);
  SELECT COUNT(DISTINCT SERIES) INTO :n_s FROM SR_DB.ML.TMP_LEV_SERIES;
  IF (n_s = 0) THEN
    RETURN 0;
  END IF;

  -- distribution share model
  CREATE OR REPLACE TEMPORARY TABLE SR_DB.ML.TMP_LEV_TRAIN AS
  SELECT SERIES, TS, Y_DIST AS Y FROM SR_DB.ML.TMP_LEV_SERIES
  WHERE Y_DIST IS NOT NULL AND TS < (SELECT MAX(TS) FROM SR_DB.ML.TMP_LEV_SERIES);
  CREATE OR REPLACE TEMPORARY TABLE SR_DB.ML.TMP_LEV_TEST AS
  SELECT SERIES, TS, Y_DIST AS Y FROM SR_DB.ML.TMP_LEV_SERIES
  WHERE Y_DIST IS NOT NULL AND TS = (SELECT MAX(TS) FROM SR_DB.ML.TMP_LEV_SERIES);
  CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION SR_DB.ML.AD_LEVERS(
    INPUT_DATA => TABLE(SR_DB.ML.TMP_LEV_TRAIN), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
    TARGET_COLNAME => 'Y', LABEL_COLNAME => '');
  CALL SR_DB.ML.AD_LEVERS!DETECT_ANOMALIES(
    INPUT_DATA => TABLE(SR_DB.ML.TMP_LEV_TEST), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
    TARGET_COLNAME => 'Y', CONFIG_OBJECT => {'prediction_interval': 0.95, 'on_error': 'skip'});
  INSERT INTO SR_DB.ML.AD_LEVERS_RESULT (RUN_ID, MARKET_ID, BRAND, SIGNAL, TS, Y, LOWER_BOUND, UPPER_BOUND, FLAGGED)
  SELECT :P_RUN_ID, SERIES[0]::VARCHAR, SERIES[1]::VARCHAR, 'DIST_DROP', TS, Y, LOWER_BOUND, UPPER_BOUND,
         COALESCE(IS_ANOMALY AND Y < LOWER_BOUND, FALSE)
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  -- price index model
  CREATE OR REPLACE TEMPORARY TABLE SR_DB.ML.TMP_LEV_TRAIN AS
  SELECT SERIES, TS, Y_PRICE AS Y FROM SR_DB.ML.TMP_LEV_SERIES
  WHERE Y_PRICE IS NOT NULL AND TS < (SELECT MAX(TS) FROM SR_DB.ML.TMP_LEV_SERIES);
  CREATE OR REPLACE TEMPORARY TABLE SR_DB.ML.TMP_LEV_TEST AS
  SELECT SERIES, TS, Y_PRICE AS Y FROM SR_DB.ML.TMP_LEV_SERIES
  WHERE Y_PRICE IS NOT NULL AND TS = (SELECT MAX(TS) FROM SR_DB.ML.TMP_LEV_SERIES);
  CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION SR_DB.ML.AD_LEVERS_PRICE(
    INPUT_DATA => TABLE(SR_DB.ML.TMP_LEV_TRAIN), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
    TARGET_COLNAME => 'Y', LABEL_COLNAME => '');
  CALL SR_DB.ML.AD_LEVERS_PRICE!DETECT_ANOMALIES(
    INPUT_DATA => TABLE(SR_DB.ML.TMP_LEV_TEST), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
    TARGET_COLNAME => 'Y', CONFIG_OBJECT => {'prediction_interval': 0.95, 'on_error': 'skip'});
  INSERT INTO SR_DB.ML.AD_LEVERS_RESULT (RUN_ID, MARKET_ID, BRAND, SIGNAL, TS, Y, LOWER_BOUND, UPPER_BOUND, FLAGGED)
  SELECT :P_RUN_ID, SERIES[0]::VARCHAR, SERIES[1]::VARCHAR, 'PRICE_RISE', TS, Y, LOWER_BOUND, UPPER_BOUND,
         COALESCE(IS_ANOMALY AND Y > UPPER_BOUND, FALSE)
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  UPDATE SR_DB.APP.EARLY_WARNING e
     SET ML_CONFIRMED = TRUE
    FROM SR_DB.ML.AD_LEVERS_RESULT a
   WHERE e.RUN_ID = :P_RUN_ID AND a.RUN_ID = :P_RUN_ID AND a.FLAGGED
     AND a.MARKET_ID = e.MARKET_ID AND a.BRAND = e.BRAND AND a.SIGNAL = e.SIGNAL;
  n := SQLROWCOUNT;
  RETURN n;
END;
$$;
