-- L14 observability and cost: pipeline health (E03, E17), exact costs by day and by run, and the run-cost view the
-- Trust page reads. Procedures and tables as SR_DEV; the hourly health task as SR_APP.
USE ROLE SR_DEV;

CREATE TABLE IF NOT EXISTS SR_DB.OPS.HEALTH_LOG (
  CHECKED_AT  TIMESTAMP_LTZ NOT NULL,
  OBJECT_TYPE VARCHAR(16)   NOT NULL,   -- DYNAMIC_TABLE | TASK | TASK_RUN | STREAM | ALERT | RUN
  OBJECT_NAME VARCHAR       NOT NULL,
  STATE       VARCHAR(8)    NOT NULL,   -- OK | WARN | FAILED
  DETAIL      VARIANT
);

-- Health checks need SHOW, which runs here in the task's session, never in the app.
CREATE OR REPLACE PROCEDURE SR_DB.OPS.SP_HEALTH_CHECK()
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  t TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
BEGIN
  DELETE FROM SR_DB.OPS.HEALTH_LOG WHERE CHECKED_AT < DATEADD(day, -14, CURRENT_TIMESTAMP());

  INSERT INTO SR_DB.OPS.HEALTH_LOG                                   -- latest refresh of each dynamic table
  SELECT :t, 'DYNAMIC_TABLE', NAME, IFF(STATE IN ('FAILED', 'UPSTREAM_FAILED'), 'FAILED', 'OK'),
         OBJECT_CONSTRUCT('state', STATE, 'message', STATE_MESSAGE, 'refresh_end', REFRESH_END_TIME)
  FROM TABLE(SR_DB.INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(NAME_PREFIX => 'SR_DB.CORE.', RESULT_LIMIT => 1000))
  WHERE STATE NOT IN ('SCHEDULED', 'EXECUTING')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY REFRESH_START_TIME DESC) = 1;

  SHOW TASKS IN SCHEMA SR_DB.OPS;                                    -- the triggered and hourly tasks must be started
  INSERT INTO SR_DB.OPS.HEALTH_LOG
  SELECT :t, 'TASK', "name", IFF("name" IN ('T_RUN_WEEK', 'T_HEALTH') AND "state" <> 'started', 'FAILED', 'OK'),
         OBJECT_CONSTRUCT('state', "state", 'schedule', "schedule")
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  INSERT INTO SR_DB.OPS.HEALTH_LOG                                   -- last finished run of each task
  SELECT :t, 'TASK_RUN', NAME, IFF(STATE = 'FAILED', 'WARN', 'OK'),
         OBJECT_CONSTRUCT('state', STATE, 'error', ERROR_MESSAGE, 'completed', COMPLETED_TIME)
  FROM TABLE(SR_DB.INFORMATION_SCHEMA.TASK_HISTORY(RESULT_LIMIT => 1000))
  WHERE SCHEMA_NAME = 'OPS' AND STATE IN ('SUCCEEDED', 'FAILED', 'CANCELLED', 'SKIPPED')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY COMPLETED_TIME DESC) = 1;

  SHOW STREAMS IN SCHEMA SR_DB.OPS;
  INSERT INTO SR_DB.OPS.HEALTH_LOG
  SELECT :t, 'STREAM', "name",
         CASE WHEN "stale"::VARCHAR = 'true' THEN 'FAILED'
              WHEN "stale_after" < DATEADD(day, 2, CURRENT_TIMESTAMP()) THEN 'WARN' ELSE 'OK' END,
         OBJECT_CONSTRUCT('stale', "stale", 'stale_after', "stale_after")
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  SHOW ALERTS IN SCHEMA SR_DB.OPS;
  INSERT INTO SR_DB.OPS.HEALTH_LOG
  SELECT :t, 'ALERT', "name", IFF("state" <> 'started', 'FAILED', 'OK'), OBJECT_CONSTRUCT('state', "state")
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  INSERT INTO SR_DB.OPS.HEALTH_LOG                                   -- a weekly product should not go 8 days silent
  SELECT :t, 'RUN', 'LAST_SUCCEEDED',
         IFF(MAX(ENDED_AT) IS NULL OR MAX(ENDED_AT) < DATEADD(day, -8, CURRENT_TIMESTAMP()), 'WARN', 'OK'),
         OBJECT_CONSTRUCT('last_succeeded', MAX(ENDED_AT))
  FROM SR_DB.OPS.RUN_LOG WHERE STATUS = 'SUCCEEDED';
  RETURN 0;
END;
$$;

CREATE OR REPLACE VIEW SR_DB.OPS.V_HEALTH_LATEST
COMMENT = 'Newest health check per object (Trust page "Pipeline health")'
AS
SELECT CHECKED_AT, OBJECT_TYPE, OBJECT_NAME, STATE, DETAIL FROM SR_DB.OPS.HEALTH_LOG
QUALIFY ROW_NUMBER() OVER (PARTITION BY OBJECT_TYPE, OBJECT_NAME ORDER BY CHECKED_AT DESC) = 1;

-- Exact costs. Reading ACCOUNT_USAGE needs GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE SR_DEV
-- (ACCOUNTADMIN). Without it the Trust page shows estimates only, marked as such.
CREATE TABLE IF NOT EXISTS SR_DB.OPS.COST_DAILY (
  USAGE_DATE DATE NOT NULL, SOURCE VARCHAR(16) NOT NULL, INTERFACE VARCHAR(16) NOT NULL DEFAULT '-',
  CREDITS NUMBER(18,6), TOKENS NUMBER(18,0), SNAPSHOT_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (USAGE_DATE, SOURCE, INTERFACE)
);
CREATE TABLE IF NOT EXISTS SR_DB.OPS.COST_RUN (
  RUN_ID VARCHAR(36) NOT NULL PRIMARY KEY, WAREHOUSE_CREDITS NUMBER(18,6), AI_CREDITS NUMBER(18,6),
  AI_TOKENS NUMBER(18,0), SNAPSHOT_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- TEAM_USERS: the team's user names, to separate our CoCo usage from other teams' on a shared account
MERGE INTO SR_DB.OPS.SETTINGS t
USING (SELECT 'TEAM_USERS' AS SETTING_KEY, PARSE_JSON('[]') AS SETTING_VALUE,
              'JSON array of the team''s Snowflake user names (CoCo cost on the Trust page)' AS DESCRIPTION) s
ON t.SETTING_KEY = s.SETTING_KEY
WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_VALUE, DESCRIPTION) VALUES (s.SETTING_KEY, s.SETTING_VALUE, s.DESCRIPTION);

-- Run by hand once a day and before the dry run: CALL SR_DB.OPS.SP_COST_SNAPSHOT(14);
-- Each source loads in its own block, so a view that is missing on this account (they are recent) does not stop
-- the others; the return value counts the sources loaded. Column names follow L14; verify them on the account.
CREATE OR REPLACE PROCEDURE SR_DB.OPS.SP_COST_SNAPSHOT(P_DAYS NUMBER DEFAULT 14)
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  loaded NUMBER DEFAULT 0;
  since  TIMESTAMP_LTZ DEFAULT DATEADD(day, -P_DAYS, CURRENT_TIMESTAMP());
BEGIN
  BEGIN
    MERGE INTO SR_DB.OPS.COST_DAILY t
    USING (SELECT TO_DATE(START_TIME) AS USAGE_DATE, 'WAREHOUSES' AS SOURCE, '-' AS INTERFACE,
                  SUM(CREDITS_USED) AS CREDITS, NULL AS TOKENS
           FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
           WHERE WAREHOUSE_NAME IN ('SR_WH_XS', 'SR_WH_M') AND START_TIME >= :since GROUP BY 1) s
    ON t.USAGE_DATE = s.USAGE_DATE AND t.SOURCE = s.SOURCE AND t.INTERFACE = s.INTERFACE
    WHEN MATCHED THEN UPDATE SET t.CREDITS = s.CREDITS, t.TOKENS = s.TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (USAGE_DATE, SOURCE, INTERFACE, CREDITS, TOKENS) VALUES (s.USAGE_DATE, s.SOURCE, s.INTERFACE, s.CREDITS, s.TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    MERGE INTO SR_DB.OPS.COST_DAILY t
    USING (SELECT TO_DATE(USAGE_TIME) AS USAGE_DATE, 'AI_FUNCTIONS' AS SOURCE, '-' AS INTERFACE,
                  SUM(TOKEN_CREDITS) AS CREDITS, SUM(TOKENS) AS TOKENS
           FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY
           WHERE STARTSWITH(QUERY_TAG, 'SR' || CHR(124)) AND USAGE_TIME >= :since GROUP BY 1) s
    ON t.USAGE_DATE = s.USAGE_DATE AND t.SOURCE = s.SOURCE AND t.INTERFACE = s.INTERFACE
    WHEN MATCHED THEN UPDATE SET t.CREDITS = s.CREDITS, t.TOKENS = s.TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (USAGE_DATE, SOURCE, INTERFACE, CREDITS, TOKENS) VALUES (s.USAGE_DATE, s.SOURCE, s.INTERFACE, s.CREDITS, s.TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    MERGE INTO SR_DB.OPS.COST_DAILY t
    USING (SELECT TO_DATE(START_TIME) AS USAGE_DATE, 'AGENT_COWORK' AS SOURCE, '-' AS INTERFACE,
                  SUM(TOKEN_CREDITS) AS CREDITS, SUM(TOKENS) AS TOKENS
           FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COWORK_USAGE_HISTORY
           WHERE AGENT_NAME = 'SHARE_RADAR_AGENT' AND START_TIME >= :since GROUP BY 1) s
    ON t.USAGE_DATE = s.USAGE_DATE AND t.SOURCE = s.SOURCE AND t.INTERFACE = s.INTERFACE
    WHEN MATCHED THEN UPDATE SET t.CREDITS = s.CREDITS, t.TOKENS = s.TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (USAGE_DATE, SOURCE, INTERFACE, CREDITS, TOKENS) VALUES (s.USAGE_DATE, s.SOURCE, s.INTERFACE, s.CREDITS, s.TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    MERGE INTO SR_DB.OPS.COST_DAILY t
    USING (SELECT TO_DATE(START_TIME) AS USAGE_DATE, 'AGENT_API' AS SOURCE, '-' AS INTERFACE,
                  SUM(TOKEN_CREDITS) AS CREDITS, SUM(TOKENS) AS TOKENS
           FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
           WHERE AGENT_NAME = 'SHARE_RADAR_AGENT' AND START_TIME >= :since GROUP BY 1) s
    ON t.USAGE_DATE = s.USAGE_DATE AND t.SOURCE = s.SOURCE AND t.INTERFACE = s.INTERFACE
    WHEN MATCHED THEN UPDATE SET t.CREDITS = s.CREDITS, t.TOKENS = s.TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (USAGE_DATE, SOURCE, INTERFACE, CREDITS, TOKENS) VALUES (s.USAGE_DATE, s.SOURCE, s.INTERFACE, s.CREDITS, s.TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    MERGE INTO SR_DB.OPS.COST_DAILY t
    USING (SELECT TO_DATE(c.USAGE_TIME) AS USAGE_DATE, 'COCO' AS SOURCE, COALESCE(c.INTERFACE, '-') AS INTERFACE,
                  SUM(c.TOKEN_CREDITS) AS CREDITS, SUM(c.TOKENS) AS TOKENS
           FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY c
           JOIN SNOWFLAKE.ACCOUNT_USAGE.USERS u ON u.USER_ID = c.USER_ID
           WHERE ARRAY_CONTAINS(u.NAME::VARIANT, SR_DB.OPS.CFG('TEAM_USERS')::ARRAY) AND c.USAGE_TIME >= :since
           GROUP BY 1, 3) s
    ON t.USAGE_DATE = s.USAGE_DATE AND t.SOURCE = s.SOURCE AND t.INTERFACE = s.INTERFACE
    WHEN MATCHED THEN UPDATE SET t.CREDITS = s.CREDITS, t.TOKENS = s.TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (USAGE_DATE, SOURCE, INTERFACE, CREDITS, TOKENS) VALUES (s.USAGE_DATE, s.SOURCE, s.INTERFACE, s.CREDITS, s.TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN                                                              -- per run: the run ID is the tag's middle part
    MERGE INTO SR_DB.OPS.COST_RUN t
    USING (
      WITH wh AS (
        SELECT SPLIT_PART(SPLIT_PART(QUERY_TAG, 'run=', 2), '|', 1) AS RUN_ID, SUM(CREDITS_ATTRIBUTED_COMPUTE) AS WAREHOUSE_CREDITS
        FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
        WHERE QUERY_TAG LIKE 'SR|run=%' AND START_TIME >= :since GROUP BY 1
      ), ai AS (
        SELECT SPLIT_PART(SPLIT_PART(QUERY_TAG, 'run=', 2), '|', 1) AS RUN_ID, SUM(TOKEN_CREDITS) AS AI_CREDITS, SUM(TOKENS) AS AI_TOKENS
        FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY
        WHERE QUERY_TAG LIKE 'SR|run=%' AND USAGE_TIME >= :since GROUP BY 1
      )
      SELECT COALESCE(wh.RUN_ID, ai.RUN_ID) AS RUN_ID, wh.WAREHOUSE_CREDITS, ai.AI_CREDITS, ai.AI_TOKENS
      FROM wh FULL OUTER JOIN ai ON ai.RUN_ID = wh.RUN_ID) s
    ON t.RUN_ID = s.RUN_ID
    WHEN MATCHED THEN UPDATE SET t.WAREHOUSE_CREDITS = s.WAREHOUSE_CREDITS, t.AI_CREDITS = s.AI_CREDITS,
                                 t.AI_TOKENS = s.AI_TOKENS, t.SNAPSHOT_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (RUN_ID, WAREHOUSE_CREDITS, AI_CREDITS, AI_TOKENS)
                          VALUES (s.RUN_ID, s.WAREHOUSE_CREDITS, s.AI_CREDITS, s.AI_TOKENS);
    loaded := loaded + 1;
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  RETURN loaded;
END;
$$;

CREATE OR REPLACE VIEW SR_DB.OPS.V_RUN_COST          -- estimate now, exact once the snapshot has it
COMMENT = 'Cost per run: the live estimate, replaced by exact credits once SP_COST_SNAPSHOT has them'
AS
SELECT r.RUN_ID, r.TRIGGER_TYPE, r.AS_OF_WEEK, r.STATUS, DATEDIFF(second, r.STARTED_AT, r.ENDED_AT) AS SECONDS,
       r.CREDITS_EST, c.WAREHOUSE_CREDITS, c.AI_CREDITS,
       COALESCE(c.AI_TOKENS, b.TOKENS_IN + b.TOKENS_OUT) AS AI_TOKENS, b.MODEL, b.GENERATOR,
       IFF(c.RUN_ID IS NULL, 'ESTIMATE', 'EXACT') AS COST_BASIS, r.STARTED_AT
FROM SR_DB.OPS.RUN_LOG r
LEFT JOIN SR_DB.OPS.COST_RUN c ON c.RUN_ID = r.RUN_ID
LEFT JOIN SR_DB.APP.BRIEF b ON b.BRIEF_ID = r.BRIEF_ID;

GRANT SELECT ON VIEW  SR_DB.OPS.V_HEALTH_LATEST TO ROLE SR_UI;
GRANT SELECT ON TABLE SR_DB.OPS.COST_DAILY      TO ROLE SR_UI;
GRANT SELECT ON VIEW  SR_DB.OPS.V_RUN_COST      TO ROLE SR_UI;

