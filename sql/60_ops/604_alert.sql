-- SR-054 · L9 delivery: an alert on new data in APP.BRIEF sends each newly published brief by email (and to Teams
-- when TEAMS_ENABLED, stretch SR-055). Failures are logged and retried at the next evaluation, at most 3 times (E13).
-- An alert on new data cannot be run by hand; for rehearsals, CALL SR_DB.APP.SP_NOTIFY_NEW_BRIEFS() directly.
USE ROLE SR_DEV;
CREATE OR REPLACE PROCEDURE SR_DB.APP.SP_NOTIFY_NEW_BRIEFS()
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  n     NUMBER DEFAULT 0;
  rcpts ARRAY;
  teams BOOLEAN DEFAULT FALSE;
  rs    RESULTSET DEFAULT (SELECT BRIEF_ID, HEADLINE, BODY_HTML, NOTIFY_ATTEMPTS FROM SR_DB.APP.BRIEF
                           WHERE STATUS = 'PUBLISHED' AND NOTIFIED_AT IS NULL AND NOTIFY_ATTEMPTS < 3);
  c     CURSOR FOR rs;
BEGIN
  SELECT ARRAY_AGG(VALUE::VARCHAR) INTO :rcpts FROM TABLE(FLATTEN(INPUT => SR_DB.OPS.CFG('NOTIFY_EMAILS')));
  SELECT COALESCE(SR_DB.OPS.CFG('TEAMS_ENABLED')::BOOLEAN, FALSE) INTO :teams;
  FOR r IN c DO
    LET bid   VARCHAR := r.BRIEF_ID;
    LET subj  VARCHAR := 'Share Radar: ' || r.HEADLINE;
    LET html  VARCHAR := r.BODY_HTML;
    LET first BOOLEAN := (r.NOTIFY_ATTEMPTS = 0);
    BEGIN
      CALL SYSTEM$SEND_SNOWFLAKE_NOTIFICATION(
        SNOWFLAKE.NOTIFICATION.TEXT_HTML(:html),
        SNOWFLAKE.NOTIFICATION.EMAIL_INTEGRATION_CONFIG('SR_EMAIL_INT', :subj, :rcpts));
      UPDATE SR_DB.APP.BRIEF SET NOTIFIED_AT = CURRENT_TIMESTAMP(), NOTIFY_ATTEMPTS = NOTIFY_ATTEMPTS + 1 WHERE BRIEF_ID = :bid;
      INSERT INTO SR_DB.OPS.NOTIFY_LOG (BRIEF_ID, CHANNEL, STATUS) VALUES (:bid, 'EMAIL', 'SENT');
      n := n + 1;
    EXCEPTION
      WHEN OTHER THEN
        UPDATE SR_DB.APP.BRIEF SET NOTIFY_ATTEMPTS = NOTIFY_ATTEMPTS + 1 WHERE BRIEF_ID = :bid;
        INSERT INTO SR_DB.OPS.NOTIFY_LOG (BRIEF_ID, CHANNEL, STATUS, MESSAGE) VALUES (:bid, 'EMAIL', 'FAILED', LEFT(:SQLERRM, 1000));
    END;
    IF (teams AND first) THEN                       -- stretch SR-055: one Teams message per brief
      BEGIN
        CALL SYSTEM$SEND_SNOWFLAKE_NOTIFICATION(
          SNOWFLAKE.NOTIFICATION.TEXT_PLAIN(SNOWFLAKE.NOTIFICATION.SANITIZE_WEBHOOK_CONTENT(:subj)),
          SNOWFLAKE.NOTIFICATION.INTEGRATION('SR_TEAMS_INT'));
        INSERT INTO SR_DB.OPS.NOTIFY_LOG (BRIEF_ID, CHANNEL, STATUS) VALUES (:bid, 'TEAMS', 'SENT');
      EXCEPTION
        WHEN OTHER THEN
          INSERT INTO SR_DB.OPS.NOTIFY_LOG (BRIEF_ID, CHANNEL, STATUS, MESSAGE) VALUES (:bid, 'TEAMS', 'FAILED', LEFT(:SQLERRM, 1000));
      END;
    END IF;
  END FOR;
  RETURN n;
END;
$$;

USE ROLE SR_APP;
-- Alert on new data: no SCHEDULE, so only newly inserted BRIEF rows are evaluated
CREATE OR REPLACE ALERT SR_DB.OPS.A_NEW_BRIEF
  WAREHOUSE = SR_WH_XS
  COMMENT = 'Emails each newly published brief'
  IF (EXISTS (SELECT 1 FROM SR_DB.APP.BRIEF WHERE STATUS = 'PUBLISHED'))
  THEN CALL SR_DB.APP.SP_NOTIFY_NEW_BRIEFS();
ALTER ALERT SR_DB.OPS.A_NEW_BRIEF RESUME;
