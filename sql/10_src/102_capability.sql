-- SR-003 · L3 capability check, with the L13 E01 check as its last statement.
-- Called at the start of every run (step 2); the newest row caps the bridge mode for that run.
USE ROLE SR_DEV;

CREATE TABLE IF NOT EXISTS SR_DB.OPS.CAPABILITY (
  CHECKED_AT       TIMESTAMP_LTZ NOT NULL,
  AS_OF_WEEK       DATE          NOT NULL,
  N_WEEKS          NUMBER        NOT NULL,
  HAS_DIST         BOOLEAN       NOT NULL,
  HAS_UNITS        BOOLEAN       NOT NULL,
  HAS_BASE_VALUE   BOOLEAN       NOT NULL,
  HAS_BASE_UNITS   BOOLEAN       NOT NULL,
  HAS_STORES       BOOLEAN       NOT NULL,
  HAS_UNIVERSE     BOOLEAN       NOT NULL,
  MAX_BRIDGE_MODE  VARCHAR(1)    NOT NULL   -- 'A' | 'B' | 'C' | 'D'
);

CREATE OR REPLACE PROCEDURE SR_DB.APP.SP_CAPABILITY_CHECK()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  no_data EXCEPTION (-20001, 'NO_DATA: no facts for the as-of week');
  max_wk  DATE;
  as_of   DATE;
BEGIN
  INSERT INTO SR_DB.OPS.CAPABILITY
    (CHECKED_AT, AS_OF_WEEK, N_WEEKS, HAS_DIST, HAS_UNITS, HAS_BASE_VALUE, HAS_BASE_UNITS, HAS_STORES,
     HAS_UNIVERSE, MAX_BRIDGE_MODE)
  -- f: the last 8 weeks of facts, the columns the checks need
  WITH f AS (
    SELECT ACV_DIST_PCT, UNIT_SALES, BASE_VALUE_SALES, BASE_UNIT_SALES, STORES_SELLING
    FROM SR_DB.SRC.V_SRC_FACT_WEEKLY
    WHERE WEEK_END_DATE > DATEADD(week, -8, (SELECT MAX(WEEK_END_DATE) FROM SR_DB.SRC.V_SRC_FACT_WEEKLY))
  ),
  -- c: a column counts as present when at least 95% of rows fill it
  c AS (
    SELECT
      COALESCE(COUNT_IF(ACV_DIST_PCT IS NOT NULL)     / NULLIF(COUNT(*), 0) >= 0.95, FALSE) AS HAS_DIST,
      COALESCE(COUNT_IF(UNIT_SALES IS NOT NULL)       / NULLIF(COUNT(*), 0) >= 0.95, FALSE) AS HAS_UNITS,
      COALESCE(COUNT_IF(BASE_VALUE_SALES IS NOT NULL) / NULLIF(COUNT(*), 0) >= 0.95, FALSE) AS HAS_BASE_VALUE,
      COALESCE(COUNT_IF(BASE_UNIT_SALES IS NOT NULL)  / NULLIF(COUNT(*), 0) >= 0.95, FALSE) AS HAS_BASE_UNITS,
      COALESCE(COUNT_IF(STORES_SELLING IS NOT NULL)   / NULLIF(COUNT(*), 0) >= 0.95, FALSE) AS HAS_STORES
    FROM f
  )
  SELECT CURRENT_TIMESTAMP(),
         COALESCE((SELECT MAX(WEEK_END_DATE) FROM SR_DB.SRC.V_SRC_FACT_WEEKLY), '1900-01-01'::DATE),
         (SELECT COUNT(DISTINCT WEEK_END_DATE) FROM SR_DB.SRC.V_SRC_FACT_WEEKLY),
         c.HAS_DIST, c.HAS_UNITS, c.HAS_BASE_VALUE, c.HAS_BASE_UNITS, c.HAS_STORES,
         (SELECT COUNT(*) > 0 FROM SR_DB.INFORMATION_SCHEMA.VIEWS
           WHERE TABLE_SCHEMA = 'SRC' AND TABLE_NAME = 'V_SRC_MARKET_UNIVERSE'),
         CASE WHEN c.HAS_DIST AND c.HAS_BASE_VALUE AND c.HAS_BASE_UNITS THEN 'A'
              WHEN c.HAS_DIST AND c.HAS_UNITS THEN 'B'
              WHEN c.HAS_DIST THEN 'C'
              ELSE 'D' END
  FROM c;

  -- E01: the adapter must reach the as-of week, otherwise this week's data has not arrived
  SELECT MAX(WEEK_END_DATE) INTO :max_wk FROM SR_DB.SRC.V_SRC_FACT_WEEKLY;
  SELECT SR_DB.OPS.CFG('AS_OF_WEEK_END')::VARCHAR::DATE INTO :as_of;
  IF (max_wk IS NULL OR max_wk < as_of) THEN
    RAISE no_data;
  END IF;
  RETURN 'OK';
END;
$$;
