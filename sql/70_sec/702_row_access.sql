-- SR-056 · L12 row access. Entitlements name a user or a role, plus a category and a market; '*' means all.
-- Granting a parent market also grants its child retailers. Needs Enterprise Edition or higher; without it the
-- agent path rests on the object grants alone, and only the configured scope is ever computed.
-- CREATE OR REPLACE VIEW drops a policy, so this file reruns after ANY change in sql/50_sem (T-SEC-03).
USE ROLE SR_DEV;

CREATE TABLE IF NOT EXISTS SR_DB.OPS.ENTITLEMENT (
  PRINCIPAL_TYPE VARCHAR(4) NOT NULL,      -- USER | ROLE
  PRINCIPAL      VARCHAR    NOT NULL,      -- upper-case user or role name
  CATEGORY       VARCHAR    NOT NULL,      -- category or '*'
  MARKET_ID      VARCHAR    NOT NULL,      -- market or '*'; child markets are stored as their own rows
  GRANTED_AT     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  NOTE           VARCHAR,
  PRIMARY KEY (PRINCIPAL_TYPE, PRINCIPAL, CATEGORY, MARKET_ID)
);

CREATE OR REPLACE PROCEDURE SR_DB.OPS.SP_ENTITLE(P_TYPE VARCHAR, P_PRINCIPAL VARCHAR, P_CATEGORY VARCHAR, P_MARKET_ID VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
BEGIN
  MERGE INTO SR_DB.OPS.ENTITLEMENT t
  USING (
    SELECT UPPER(:P_TYPE) AS PRINCIPAL_TYPE, UPPER(:P_PRINCIPAL) AS PRINCIPAL, :P_CATEGORY AS CATEGORY, :P_MARKET_ID AS MARKET_ID
    UNION
    SELECT UPPER(:P_TYPE), UPPER(:P_PRINCIPAL), :P_CATEGORY, m.MARKET_ID
    FROM SR_DB.SRC.V_SRC_MARKET m WHERE m.PARENT_MARKET_ID = :P_MARKET_ID      -- a parent brings its children
  ) s
  ON t.PRINCIPAL_TYPE = s.PRINCIPAL_TYPE AND t.PRINCIPAL = s.PRINCIPAL AND t.CATEGORY = s.CATEGORY AND t.MARKET_ID = s.MARKET_ID
  WHEN NOT MATCHED THEN INSERT (PRINCIPAL_TYPE, PRINCIPAL, CATEGORY, MARKET_ID)
                        VALUES (s.PRINCIPAL_TYPE, s.PRINCIPAL, s.CATEGORY, s.MARKET_ID);
  RETURN SQLROWCOUNT;
END;
$$;

CREATE ROW ACCESS POLICY IF NOT EXISTS SR_DB.OPS.RAP_ENTITLED
  AS (P_MARKET_ID VARCHAR, P_CATEGORY VARCHAR) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('SR_DEV')                                    -- builders and admins see everything
    OR EXISTS (
      SELECT 1 FROM SR_DB.OPS.ENTITLEMENT e
      WHERE ((e.PRINCIPAL_TYPE = 'USER' AND e.PRINCIPAL = CURRENT_USER())
          OR (e.PRINCIPAL_TYPE = 'ROLE' AND IS_ROLE_IN_SESSION(e.PRINCIPAL)))
        AND e.CATEGORY  IN (P_CATEGORY, '*')
        AND e.MARKET_ID IN (P_MARKET_ID, '*'));
-- To change the body later: ALTER ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED SET BODY -> ...

-- Attach to every governed surface (DROP ALL then ADD, so a rerun never stacks or misses one)
ALTER VIEW SR_DB.SEM.V_SEM_SHARE_GRID   DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_SEM_SHARE_GRID   ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_SEM_SHARE_CHANGE DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_SEM_SHARE_CHANGE ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_TOOL_BRIDGE      DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_TOOL_BRIDGE      ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_TOOL_WHERE       DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_TOOL_WHERE       ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_TOOL_ARTEFACT    DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_TOOL_ARTEFACT    ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_TOOL_FLOW        DROP ALL ROW ACCESS POLICIES;
ALTER VIEW SR_DB.SEM.V_TOOL_FLOW        ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);
ALTER VIEW SR_DB.SEM.V_TOOL_BRIEF       DROP ALL ROW ACCESS POLICIES;            -- MARKET_ID is the parent market
ALTER VIEW SR_DB.SEM.V_TOOL_BRIEF       ADD ROW ACCESS POLICY SR_DB.OPS.RAP_ENTITLED ON (MARKET_ID, CATEGORY);

-- Demo entitlement: analysts, and so judges, see the scope category in the parent market and its retailers
EXECUTE IMMEDIATE $$
DECLARE
  cat VARCHAR;
  mkt VARCHAR;
BEGIN
  SELECT SR_DB.OPS.CFG('SCOPE_CATEGORY')::VARCHAR, SR_DB.OPS.CFG('SCOPE_PARENT_MARKET')::VARCHAR INTO :cat, :mkt;
  CALL SR_DB.OPS.SP_ENTITLE('ROLE', 'SR_ANALYST', :cat, :mkt);
  RETURN 'Entitled SR_ANALYST to ' || cat || ' in ' || mkt || ' and its child markets';
END;
$$;
