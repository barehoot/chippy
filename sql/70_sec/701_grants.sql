-- SR-056 · L12 grants. Deployed after 50_sem and BEFORE 60_ops (B11). Analysts and judges never touch a table: they reach data only through the read-only app,
-- the semantic view and the tool procedures. Builders and the pipeline use roles viewers cannot assume.
-- ORGANIZERS: blocks 1-3 need SECURITYADMIN, ACCOUNTADMIN and SYSADMIN. If the team lacks them, hand those three
-- blocks to the organizers and run blocks 4-7 as SR_ADMIN. Each ON ALL grant has its ON FUTURE twin.

-- Block 1: roles (SECURITYADMIN) -- ORGANIZERS
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS SR_UI;                 -- owns the read-only app
GRANT ROLE SR_APP     TO ROLE SR_DEV;            -- builders can act as the runtime role
GRANT ROLE SR_UI      TO ROLE SR_DEV;            -- builders deploy the read-only app as SR_UI
GRANT ROLE SR_UI      TO ROLE SR_ADMIN;
GRANT ROLE SR_ANALYST TO ROLE SR_JUDGE;          -- judges are analysts, read-only

-- Block 2: account level (ACCOUNTADMIN) -- ORGANIZERS
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK  ON ACCOUNT TO ROLE SR_APP;
GRANT EXECUTE ALERT ON ACCOUNT TO ROLE SR_APP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SR_DEV;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SR_APP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SR_ANALYST;
-- optional: GRANT READ SESSION ON ACCOUNT TO ROLE SR_UI;              -- only to show the viewer's name in the app
-- optional: GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE SR_DEV;   -- exact costs on the Trust page (L14)

-- Block 3: warehouses (SYSADMIN owns them) -- ORGANIZERS if SYSADMIN is not available
USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE SR_WH_XS TO ROLE SR_APP;
GRANT USAGE ON WAREHOUSE SR_WH_M  TO ROLE SR_APP;
GRANT USAGE ON WAREHOUSE SR_WH_XS TO ROLE SR_UI;
GRANT USAGE ON WAREHOUSE SR_WH_XS TO ROLE SR_ANALYST;   -- the agent's tools run on SR_WH_XS as the caller

-- Block 4: builders
USE ROLE SR_ADMIN;
GRANT USAGE ON DATABASE SR_DB TO ROLE SR_DEV;
GRANT ALL ON ALL SCHEMAS IN DATABASE SR_DB TO ROLE SR_DEV;   -- every CREATE privilege, but not ML class instances
GRANT ALL ON FUTURE SCHEMAS IN DATABASE SR_DB TO ROLE SR_DEV;
GRANT CREATE SNOWFLAKE.ML.ANOMALY_DETECTION ON SCHEMA SR_DB.ML TO ROLE SR_DEV;
GRANT CREATE SNOWFLAKE.ML.TOP_INSIGHTS      ON SCHEMA SR_DB.ML TO ROLE SR_DEV;

-- Block 5: runtime (SR_APP): read SRC and CORE, write APP, ML and OPS, refresh dynamic tables, run tasks
GRANT USAGE ON DATABASE SR_DB TO ROLE SR_APP;
GRANT USAGE ON SCHEMA SR_DB.SRC  TO ROLE SR_APP;
GRANT USAGE ON SCHEMA SR_DB.CORE TO ROLE SR_APP;
GRANT USAGE ON SCHEMA SR_DB.ML   TO ROLE SR_APP;
GRANT USAGE ON SCHEMA SR_DB.APP  TO ROLE SR_APP;
GRANT USAGE ON SCHEMA SR_DB.OPS  TO ROLE SR_APP;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SR_DB.SRC TO ROLE SR_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SR_DB.SRC TO ROLE SR_APP;
GRANT SELECT, OPERATE ON ALL DYNAMIC TABLES    IN SCHEMA SR_DB.CORE TO ROLE SR_APP;   -- OPERATE: replay refresh
GRANT SELECT, OPERATE ON FUTURE DYNAMIC TABLES IN SCHEMA SR_DB.CORE TO ROLE SR_APP;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SR_DB.CORE TO ROLE SR_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SR_DB.CORE TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA SR_DB.ML  TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SR_DB.ML  TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT SELECT ON ALL VIEWS    IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT USAGE ON ALL PROCEDURES    IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA SR_DB.APP TO ROLE SR_APP;
GRANT USAGE ON ALL PROCEDURES    IN SCHEMA SR_DB.OPS TO ROLE SR_APP;    -- SP_HEALTH_CHECK, SP_COST_SNAPSHOT
GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT USAGE ON ALL FUNCTIONS     IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT USAGE ON FUTURE FUNCTIONS  IN SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT READ ON STAGE SR_DB.APP.CODE TO ROLE SR_APP;
GRANT CREATE TABLE ON SCHEMA SR_DB.ML TO ROLE SR_APP;                      -- temporary tables in the ML procedures
GRANT CREATE SNOWFLAKE.ML.ANOMALY_DETECTION ON SCHEMA SR_DB.ML TO ROLE SR_APP;
GRANT CREATE SNOWFLAKE.ML.TOP_INSIGHTS      ON SCHEMA SR_DB.ML TO ROLE SR_APP;
GRANT CREATE STREAM, CREATE TASK, CREATE ALERT ON SCHEMA SR_DB.OPS TO ROLE SR_APP;
GRANT CREATE STREAMLIT, CREATE STAGE ON SCHEMA SR_DB.APP TO ROLE SR_APP;   -- owns the admin app
