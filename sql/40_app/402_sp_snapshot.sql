-- SR-024 · L6 snapshot of the facts behind this run (feeds R3_RESTATE): row count, value and HASH_AGG per
-- week x market, for the weeks in any reporting period and the scope markets. Non-critical step (3).
USE ROLE SR_DEV;
CREATE OR REPLACE PROCEDURE SR_DB.APP.SP_SNAPSHOT(P_RUN_ID VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  n      NUMBER DEFAULT 0;
  parent VARCHAR;
BEGIN
  EXECUTE IMMEDIATE 'ALTER SESSION SET QUERY_TAG = ''SR|run=' || P_RUN_ID || '|step=SNAPSHOT''';
  SELECT SR_DB.OPS.CFG('SCOPE_PARENT_MARKET')::VARCHAR INTO :parent;
  DELETE FROM SR_DB.OPS.FACT_SNAPSHOT WHERE RUN_ID = :P_RUN_ID;
  INSERT INTO SR_DB.OPS.FACT_SNAPSHOT (RUN_ID, WEEK_END_DATE, MARKET_ID, ROW_COUNT, VALUE_SUM, ROW_HASH)
  SELECT :P_RUN_ID, f.WEEK_END_DATE, f.MARKET_ID, COUNT(*), SUM(f.VALUE_SALES),
         HASH_AGG(f.PRODUCT_ID, f.VALUE_SALES, f.UNIT_SALES, f.ACV_DIST_PCT)
  FROM SR_DB.SRC.V_SRC_FACT_WEEKLY f
  WHERE f.WEEK_END_DATE IN (SELECT WEEK_END_DATE FROM SR_DB.CORE.DT_PERIOD_WEEK)
    AND f.MARKET_ID IN (SELECT MARKET_ID FROM SR_DB.SRC.V_SRC_MARKET WHERE MARKET_ID = :parent OR PARENT_MARKET_ID = :parent)
  GROUP BY f.WEEK_END_DATE, f.MARKET_ID;
  n := SQLROWCOUNT;
  RETURN n;
END;
$$;
