-- T-DET-01 (SR-020): a candidate PASSED_GATES exactly when it meets all three gates, recomputed from
-- DT_SHARE_COMPARE and OPS.SETTINGS (the z-score is the candidate's own; T-DET-02 covers when it exists).
SET TEST_ID = 'T-DET-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- gates: current thresholds
WITH gates AS (
  SELECT (SELECT SETTING_VALUE::FLOAT FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'MIN_SHARE_PTS')      AS MIN_PTS,
         (SELECT SETTING_VALUE::FLOAT FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'MIN_VALUE_AT_STAKE') AS MIN_VAL,
         (SELECT SETTING_VALUE::FLOAT FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'MIN_Z')              AS MIN_Z
),
-- expect: the gate decision recomputed per candidate
expect AS (
  SELECT sc.SHIFT_ID, sc.CMP_CODE, sc.MARKET_ID, sc.BRAND, sc.PASSED_GATES,
         COALESCE(100 * ABS(c.D_SHARE) >= g.MIN_PTS
                  AND ABS(c.D_SHARE * c.CS1) >= g.MIN_VAL
                  AND (sc.Z_SCORE IS NULL OR ABS(sc.Z_SCORE) >= g.MIN_Z), FALSE) AS SHOULD_PASS
  FROM SR_DB.APP.SHIFT_CANDIDATE sc
  JOIN SR_DB.CORE.DT_SHARE_COMPARE c
    ON c.CMP_CODE = sc.CMP_CODE AND c.MARKET_ID = sc.MARKET_ID AND c.CATEGORY = sc.CATEGORY AND c.BRAND = sc.BRAND
   AND EQUAL_NULL(c.MANUFACTURER, sc.MANUFACTURER)
  CROSS JOIN gates g
  WHERE sc.RUN_ID = $RUN_UNDER_TEST
),
failures AS (
  SELECT SHIFT_ID, CMP_CODE, MARKET_ID, BRAND, PASSED_GATES, SHOULD_PASS FROM expect WHERE PASSED_GATES <> SHOULD_PASS
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
