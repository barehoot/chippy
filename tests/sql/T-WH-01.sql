-- T-WH-01 (SR-023): for selected shifts in the parent market, PERF_PTS + MIX_PTS over all retailers plus the
-- remainder sums to 100 x D_SHARE within 1e-6.
SET TEST_ID = 'T-WH-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH parts AS (
  SELECT SHIFT_ID, SUM(PERF_PTS + MIX_PTS) AS PTS
  FROM SR_DB.APP.SHIFT_WHERE WHERE RUN_ID = $RUN_UNDER_TEST AND METHOD = 'EXACT_RETAILER'
  GROUP BY SHIFT_ID
),
failures AS (
  SELECT r.SHIFT_ID, r.BRAND, 100 * r.D_SHARE AS CHANGE_PTS, p.PTS
  FROM SR_DB.APP.SHIFT_RANKED r
  LEFT JOIN parts p ON p.SHIFT_ID = r.SHIFT_ID
  WHERE r.RUN_ID = $RUN_UNDER_TEST AND r.SELECTED
    AND r.MARKET_ID = (SELECT SETTING_VALUE::VARCHAR FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'SCOPE_PARENT_MARKET')
    AND (p.PTS IS NULL OR ABS(p.PTS - 100 * r.D_SHARE) >= 1e-6)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
