-- T-SEC-02 (SR-056): a USER entitlement for one retailer, simulated with POLICY_CONTEXT (T1), lets the SEM views
-- return only that retailer's rows; a brand sold only elsewhere is not among SP_RESOLVE's candidates (they come
-- from SEM.V_TOOL_BRIDGE under the same policy), so SP_RESOLVE returns NOT_FOUND. The entitlement is removed after.
SET TEST_ID = 'T-SEC-02';
SET PARENT = (SELECT SETTING_VALUE::VARCHAR FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'SCOPE_PARENT_MARKET');
SET RET = (SELECT MIN(m.MARKET_ID) FROM SR_DB.SRC.V_SRC_MARKET m
           WHERE m.PARENT_MARKET_ID = $PARENT
             AND EXISTS (SELECT 1 FROM SR_DB.CORE.DT_SHARE_COMPARE c WHERE c.MARKET_ID = m.MARKET_ID));
SET ELSEWHERE_BRAND = (SELECT MIN(b.BRAND) FROM SR_DB.SEM.V_TOOL_BRIDGE b
                       WHERE NOT EXISTS (SELECT 1 FROM SR_DB.SEM.V_TOOL_BRIDGE x WHERE x.BRAND = b.BRAND AND x.MARKET_ID = $RET));
DELETE FROM SR_DB.OPS.ENTITLEMENT WHERE PRINCIPAL = 'SR_TEST_USER';
INSERT INTO SR_DB.OPS.ENTITLEMENT (PRINCIPAL_TYPE, PRINCIPAL, CATEGORY, MARKET_ID, NOTE)
VALUES ('USER', 'SR_TEST_USER', '*', $RET, 'T-SEC-02 simulation');
EXECUTE USING POLICY_CONTEXT(CURRENT_USER => 'SR_TEST_USER', CURRENT_ROLE => 'PUBLIC') AS
SELECT 'V_SEM_SHARE_GRID' AS VIEW_NAME, COUNT_IF(MARKET_ID <> $RET) AS LEAKED, COUNT_IF(MARKET_ID = $RET) AS OWN FROM SR_DB.SEM.V_SEM_SHARE_GRID
UNION ALL SELECT 'V_SEM_SHARE_CHANGE', COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_SEM_SHARE_CHANGE
UNION ALL SELECT 'V_TOOL_BRIDGE',      COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_TOOL_BRIDGE
UNION ALL SELECT 'V_TOOL_WHERE',       COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_TOOL_WHERE
UNION ALL SELECT 'V_TOOL_ARTEFACT',    COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_TOOL_ARTEFACT
UNION ALL SELECT 'V_TOOL_FLOW',        COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_TOOL_FLOW
UNION ALL SELECT 'V_TOOL_BRIEF',       COUNT_IF(MARKET_ID <> $RET), COUNT_IF(MARKET_ID = $RET) FROM SR_DB.SEM.V_TOOL_BRIEF
UNION ALL SELECT 'RESOLVE_CANDIDATES', COUNT(*), 0 FROM SR_DB.SEM.V_TOOL_BRIDGE WHERE BRAND = $ELSEWHERE_BRAND;
SET Q = LAST_QUERY_ID();
DELETE FROM SR_DB.OPS.ENTITLEMENT WHERE PRINCIPAL = 'SR_TEST_USER';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH r AS (SELECT $1 AS VIEW_NAME, $2 AS LEAKED, $3 AS OWN FROM TABLE(RESULT_SCAN($Q))),
failures AS (
  SELECT VIEW_NAME, LEAKED, OWN FROM r
  WHERE LEAKED > 0 OR (VIEW_NAME = 'V_SEM_SHARE_GRID' AND OWN = 0)
  UNION ALL
  SELECT 'NO_TEST_DATA', NULL, NULL WHERE $RET IS NULL OR $ELSEWHERE_BRAND IS NULL
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
