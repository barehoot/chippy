-- T-RANK-01 (SR-026): at most TOP_N rows SELECTED, none labelled POSSIBLE_DATA_EFFECT; SCORE recomputed from
-- its parts within 1e-9 (relative to the score); RANK_NO contiguous from 1.
SET TEST_ID = 'T-RANK-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- r: the run's ranked shifts with the inputs the score uses
WITH r AS (
  SELECT r.SHIFT_ID, r.RANK_NO, r.SELECTED, r.ARTEFACT_LABEL, r.ART_FACTOR, r.SCORE, r.IS_FOCUS, r.VALUE_AT_STAKE,
         c.Z_SCORE, c.ANOMALY_CONFIRMED
  FROM SR_DB.APP.SHIFT_RANKED r
  JOIN SR_DB.APP.SHIFT_CANDIDATE c ON c.RUN_ID = r.RUN_ID AND c.SHIFT_ID = r.SHIFT_ID
  WHERE r.RUN_ID = $RUN_UNDER_TEST
),
-- recomputed: the score from its parts, independently of SP_RANK
recomputed AS (
  SELECT r.*,
         CASE WHEN COALESCE(ANOMALY_CONFIRMED, FALSE)
              THEN GREATEST(COALESCE(LEAST(1, ABS(Z_SCORE) / 3), 0.5), 0.8)
              ELSE COALESCE(LEAST(1, ABS(Z_SCORE) / 3), 0.5) END                                       AS CONF,
         DECODE(ARTEFACT_LABEL, 'MARKET_MOVE', 1.0, 'MIXED', 0.6, 'POSSIBLE_DATA_EFFECT', 0.3)       AS FACTOR,
         ABS(VALUE_AT_STAKE) * CONF * FACTOR * IFF(IS_FOCUS, 1.5, 1.0)                                AS SCORE2
  FROM r
),
failures AS (
  SELECT 'TOO_MANY_SELECTED' AS PROBLEM, NULL AS SHIFT_ID, COUNT_IF(SELECTED)::FLOAT AS VAL
  FROM r HAVING COUNT_IF(SELECTED) > (SELECT SETTING_VALUE::NUMBER FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'TOP_N')
  UNION ALL
  SELECT 'SELECTED_DATA_EFFECT', SHIFT_ID, NULL FROM r WHERE SELECTED AND ARTEFACT_LABEL = 'POSSIBLE_DATA_EFFECT'
  UNION ALL
  SELECT 'SCORE', SHIFT_ID, SCORE - SCORE2 FROM recomputed
  WHERE ABS(SCORE - SCORE2) > 1e-9 * GREATEST(1, ABS(SCORE2)) OR ABS(ART_FACTOR - FACTOR) > 1e-12
  UNION ALL
  SELECT 'RANK_NOT_CONTIGUOUS', NULL, COUNT(*)::FLOAT FROM r
  HAVING COUNT(*) > 0 AND (MIN(RANK_NO) <> 1 OR MAX(RANK_NO) <> COUNT(*) OR COUNT(DISTINCT RANK_NO) <> COUNT(*))
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
