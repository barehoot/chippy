-- T-E2E-04 (SR-033): with MAX_CREDITS_PER_RUN = 0, ML_ANOMALY and TOP_INSIGHTS are SKIPPED with "credit cap" and
-- the run still SUCCEEDS (E09). The setting is restored.
SET TEST_ID = 'T-E2E-04';
EXECUTE IMMEDIATE $$
DECLARE
  fails ARRAY DEFAULT ARRAY_CONSTRUCT();
  orig  VARIANT;
  rid   VARCHAR;
  st    VARCHAR;
  n     NUMBER;
BEGIN
  IF (NOT $RUN_E2E) THEN RETURN 'SKIPPED_NO_E2E'; END IF;
  SELECT SETTING_VALUE INTO :orig FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'MAX_CREDITS_PER_RUN';
  UPDATE SR_DB.OPS.SETTINGS SET SETTING_VALUE = TO_VARIANT(0) WHERE SETTING_KEY = 'MAX_CREDITS_PER_RUN';
  BEGIN
    CALL SR_DB.APP.SP_RUN_WEEK('MANUAL', TRUE) INTO :rid;
  EXCEPTION
    WHEN OTHER THEN
      fails := ARRAY_APPEND(fails, 'SP_RUN_WEEK raised: ' || LEFT(SQLERRM, 200));
  END;
  UPDATE SR_DB.OPS.SETTINGS SET SETTING_VALUE = :orig WHERE SETTING_KEY = 'MAX_CREDITS_PER_RUN';
  SELECT STATUS INTO :st FROM SR_DB.OPS.RUN_LOG WHERE RUN_ID = :rid;
  IF (st IS NULL OR st <> 'SUCCEEDED') THEN fails := ARRAY_APPEND(fails, 'run status ' || COALESCE(st, 'none')); END IF;
  SELECT COUNT(*) INTO :n FROM SR_DB.OPS.STEP_LOG
   WHERE RUN_ID = :rid AND STEP IN ('ML_ANOMALY', 'TOP_INSIGHTS') AND STATUS = 'SKIPPED' AND MESSAGE = 'credit cap';
  IF (n <> 2) THEN fails := ARRAY_APPEND(fails, n || ' of 2 cost steps skipped for the credit cap'); END IF;
  RETURN ARRAY_TO_STRING(fails, '; ');
END;
$$;
SET Q = LAST_QUERY_ID();
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
SELECT $TEST_RUN_ID, $TEST_ID, $1 = '', IFF($1 = '', 0, ARRAY_SIZE(SPLIT($1, '; '))), TO_VARIANT($1)
FROM TABLE(RESULT_SCAN($Q)) WHERE $1 <> 'SKIPPED_NO_E2E';
