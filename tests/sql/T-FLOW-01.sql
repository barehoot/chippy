-- T-FLOW-01 (SR-025): each losing brand's outflows sum to 100 x ABS(D_SHARE) within 1e-6, for every market the run wrote flows for.
SET TEST_ID = 'T-FLOW-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- d: brand share changes in the markets with flows
WITH d AS (
  SELECT c.CMP_CODE, c.MARKET_ID, c.CATEGORY, c.BRAND, SUM(c.D_SHARE) AS D_SHARE
  FROM SR_DB.CORE.DT_SHARE_COMPARE c
  WHERE (c.CMP_CODE, c.MARKET_ID, c.CATEGORY) IN (SELECT CMP_CODE, MARKET_ID, CATEGORY FROM SR_DB.APP.SHARE_FLOW
                                                  WHERE RUN_ID = $RUN_UNDER_TEST)
  GROUP BY c.CMP_CODE, c.MARKET_ID, c.CATEGORY, c.BRAND
),
f AS (
  SELECT CMP_CODE, MARKET_ID, CATEGORY, FROM_BRAND AS BRAND, SUM(FLOW_PTS) AS PTS
  FROM SR_DB.APP.SHARE_FLOW WHERE RUN_ID = $RUN_UNDER_TEST
  GROUP BY CMP_CODE, MARKET_ID, CATEGORY, FROM_BRAND
),
failures AS (
  SELECT d.CMP_CODE, d.MARKET_ID, d.BRAND, -100 * d.D_SHARE AS EXPECTED_PTS, f.PTS
  FROM d LEFT JOIN f ON f.CMP_CODE = d.CMP_CODE AND f.MARKET_ID = d.MARKET_ID AND f.CATEGORY = d.CATEGORY AND f.BRAND = d.BRAND
  WHERE d.D_SHARE < 0 AND (f.PTS IS NULL OR ABS(f.PTS - (-100 * d.D_SHARE)) >= 1e-6)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
