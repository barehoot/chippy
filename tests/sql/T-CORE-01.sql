-- T-CORE-01 (SR-012): for every period, market and category, value shares over all brands (private label
-- included) sum to 1 within 1e-9.
SET TEST_ID = 'T-CORE-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH failures AS (
  SELECT PERIOD_CODE, MARKET_ID, CATEGORY, SUM(VALUE_SHARE) AS SHARE_SUM
  FROM SR_DB.CORE.V_SHARE_GRID
  WHERE CAT_VALUE_SALES <> 0
  GROUP BY PERIOD_CODE, MARKET_ID, CATEGORY
  HAVING ABS(SUM(VALUE_SHARE) - 1) > 1e-9
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
