-- T-SRC-02 (SR-003): last 8 weeks of facts have unique keys, %ACV in 0..100, and resolvable product and market IDs.
SET TEST_ID = 'T-SRC-02';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- f: the last 8 weeks of adapter facts
WITH f AS (
  SELECT WEEK_END_DATE, MARKET_ID, PRODUCT_ID, ACV_DIST_PCT
  FROM SR_DB.SRC.V_SRC_FACT_WEEKLY
  WHERE WEEK_END_DATE > DATEADD(week, -8, (SELECT MAX(WEEK_END_DATE) FROM SR_DB.SRC.V_SRC_FACT_WEEKLY))
),
failures AS (
  -- duplicate grain
  SELECT 'DUPLICATE' AS PROBLEM, WEEK_END_DATE, MARKET_ID, PRODUCT_ID, COUNT(*)::FLOAT AS VALUE
  FROM f GROUP BY WEEK_END_DATE, MARKET_ID, PRODUCT_ID HAVING COUNT(*) > 1
  UNION ALL
  -- %ACV outside 0..100
  SELECT 'ACV_RANGE', WEEK_END_DATE, MARKET_ID, PRODUCT_ID, ACV_DIST_PCT::FLOAT
  FROM f WHERE ACV_DIST_PCT < 0 OR ACV_DIST_PCT > 100
  UNION ALL
  -- product not in V_SRC_PRODUCT
  SELECT 'PRODUCT_UNRESOLVED', MIN(f.WEEK_END_DATE), MIN(f.MARKET_ID), f.PRODUCT_ID, NULL
  FROM f LEFT JOIN SR_DB.SRC.V_SRC_PRODUCT p ON p.PRODUCT_ID = f.PRODUCT_ID
  WHERE p.PRODUCT_ID IS NULL GROUP BY f.PRODUCT_ID
  UNION ALL
  -- market not in V_SRC_MARKET
  SELECT 'MARKET_UNRESOLVED', MIN(f.WEEK_END_DATE), f.MARKET_ID, NULL, NULL
  FROM f LEFT JOIN SR_DB.SRC.V_SRC_MARKET m ON m.MARKET_ID = f.MARKET_ID
  WHERE m.MARKET_ID IS NULL GROUP BY f.MARKET_ID
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
