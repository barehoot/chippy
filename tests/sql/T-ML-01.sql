-- T-ML-01 (SR-021): ANOMALY_WEEKS is between 0 and 4; ANOMALY_CONFIRMED equals ANOMALY_WEEKS >= 2; if the
-- ML_ANOMALY step logged WARN, the run still SUCCEEDED (E07).
SET TEST_ID = 'T-ML-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH failures AS (
  SELECT 'RANGE_OR_FLAG' AS PROBLEM, SHIFT_ID AS ID, ANOMALY_WEEKS::VARCHAR AS VAL, ANOMALY_CONFIRMED::VARCHAR AS FLAG
  FROM SR_DB.APP.SHIFT_CANDIDATE
  WHERE RUN_ID = $RUN_UNDER_TEST
    AND (COALESCE(ANOMALY_WEEKS, 0) NOT BETWEEN 0 AND 4
         OR COALESCE(ANOMALY_CONFIRMED, FALSE) <> (COALESCE(ANOMALY_WEEKS, 0) >= 2))
  UNION ALL
  SELECT 'WARN_BUT_RUN_NOT_SUCCEEDED', s.RUN_ID, s.STATUS, r.STATUS
  FROM SR_DB.OPS.STEP_LOG s JOIN SR_DB.OPS.RUN_LOG r ON r.RUN_ID = s.RUN_ID
  WHERE s.RUN_ID = $RUN_UNDER_TEST AND s.STEP = 'ML_ANOMALY' AND s.STATUS = 'WARN' AND r.STATUS <> 'SUCCEEDED'
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
