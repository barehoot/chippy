-- T-ART-02 (SR-024): R6_GAP rows exist exactly where CAT_WEEKS1 or CAT_WEEKS0 is below EXP_WEEKS in a scope market.
SET TEST_ID = 'T-ART-02';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- scope: the parent and its children
WITH scope AS (
  SELECT MARKET_ID FROM SR_DB.SRC.V_SRC_MARKET,
       (SELECT SETTING_VALUE::VARCHAR AS P FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'SCOPE_PARENT_MARKET') s
  WHERE MARKET_ID = s.P OR PARENT_MARKET_ID = s.P
),
expected AS (
  SELECT DISTINCT c.CMP_CODE, c.MARKET_ID FROM SR_DB.CORE.DT_SHARE_COMPARE c JOIN scope USING (MARKET_ID)
  WHERE c.CAT_WEEKS1 < c.EXP_WEEKS OR c.CAT_WEEKS0 < c.EXP_WEEKS
),
actual AS (
  SELECT DISTINCT CMP_CODE, MARKET_ID FROM SR_DB.APP.ARTEFACT_CHECK WHERE RUN_ID = $RUN_UNDER_TEST AND RULE_ID = 'R6_GAP'
),
failures AS (
  SELECT 'MISSING' AS PROBLEM, CMP_CODE, MARKET_ID FROM (SELECT * FROM expected MINUS SELECT * FROM actual)
  UNION ALL
  SELECT 'UNEXPECTED', CMP_CODE, MARKET_ID FROM (SELECT * FROM actual MINUS SELECT * FROM expected)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
