-- T-BR-03 (SR-022, SQL part): rows with S0 = 0, S1 = 0 or a missing category total get status NEW, EXIT or
-- NO_DATA, recomputed independently from DT_SHARE_COMPARE, and carry NULL terms.
SET TEST_ID = 'T-BR-03';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- expect: the status each edge row must have
WITH expect AS (
  SELECT c.CMP_CODE, c.MARKET_ID, c.CATEGORY, c.MANUFACTURER, c.BRAND,
         CASE WHEN c.CS1 IS NULL OR c.CS0 IS NULL THEN 'NO_DATA'
              WHEN c.S0 = 0 AND c.S1 > 0 THEN 'NEW'
              WHEN c.S1 = 0 AND c.S0 > 0 THEN 'EXIT' END AS EXPECTED_STATUS
  FROM SR_DB.CORE.DT_SHARE_COMPARE c
),
failures AS (
  SELECT e.CMP_CODE, e.MARKET_ID, e.BRAND, e.EXPECTED_STATUS, b.STATUS, b.DIST_PTS, b.VELOCITY_PTS
  FROM expect e
  JOIN SR_DB.APP.V_BRIDGE_ALL b
    ON b.CMP_CODE = e.CMP_CODE AND b.MARKET_ID = e.MARKET_ID AND b.CATEGORY = e.CATEGORY AND b.BRAND = e.BRAND
   AND EQUAL_NULL(b.MANUFACTURER, e.MANUFACTURER)
  WHERE e.EXPECTED_STATUS IS NOT NULL
    AND (b.STATUS <> e.EXPECTED_STATUS
         OR b.DIST_PTS IS NOT NULL OR b.VELOCITY_PTS IS NOT NULL OR b.PRICE_PTS IS NOT NULL OR b.PROMO_PTS IS NOT NULL)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
