-- T-CORE-03 (SR-013): each of the five reference numbers is matched within 0.05 pts (shares, in percent) or
-- 0.5% relative (sales), recomputed here from the dynamic tables, and the newest OPS.RECON_RESULT row per check
-- is PASSED. Fails if fewer than five reference rows exist.
SET TEST_ID = 'T-CORE-03';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- brand: brand totals straight from the period tables (independent of V_SHARE_GRID)
WITH brand AS (
  SELECT PERIOD_CODE, MARKET_ID, CATEGORY, BRAND, SUM(VALUE_SALES) AS V, SUM(TDP_SUM) AS T
  FROM SR_DB.CORE.DT_BRAND_PERIOD GROUP BY PERIOD_CODE, MARKET_ID, CATEGORY, BRAND
),
-- recomputed: each reference value in its own unit
recomputed AS (
  SELECT r.CHECK_ID, r.METRIC, r.REFERENCE_VALUE,
         CASE r.METRIC
           WHEN 'VALUE_SALES' THEN COALESCE(b.V, c.CAT_VALUE_SALES)
           WHEN 'VALUE_SHARE' THEN 100 * b.V / NULLIF(c.CAT_VALUE_SALES, 0)
           WHEN 'DIST_SHARE'  THEN 100 * b.T / NULLIF(c.CAT_TDP_SUM, 0)
         END AS VAL
  FROM SR_DB.TEST.FX_RECON_REFERENCE r
  LEFT JOIN SR_DB.CORE.DT_CAT_PERIOD c
    ON c.PERIOD_CODE = r.PERIOD_CODE AND c.MARKET_ID = r.MARKET_ID AND c.CATEGORY = r.CATEGORY
  LEFT JOIN brand b
    ON b.PERIOD_CODE = r.PERIOD_CODE AND b.MARKET_ID = r.MARKET_ID AND b.CATEGORY = r.CATEGORY AND b.BRAND = r.BRAND
),
latest AS (
  SELECT CHECK_ID, PASSED FROM SR_DB.OPS.RECON_RESULT
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CHECK_ID ORDER BY CHECKED_AT DESC) = 1
),
failures AS (
  SELECT 'OUT_OF_TOLERANCE' AS PROBLEM, CHECK_ID, REFERENCE_VALUE, VAL
  FROM recomputed
  WHERE VAL IS NULL
     OR (METRIC = 'VALUE_SALES' AND ABS(VAL - REFERENCE_VALUE) > 0.005 * ABS(REFERENCE_VALUE))
     OR (METRIC <> 'VALUE_SALES' AND ABS(VAL - REFERENCE_VALUE) > 0.05)
  UNION ALL
  SELECT 'RECON_NOT_PASSED', r.CHECK_ID, NULL, NULL
  FROM SR_DB.TEST.FX_RECON_REFERENCE r LEFT JOIN latest l ON l.CHECK_ID = r.CHECK_ID
  WHERE NOT COALESCE(l.PASSED, FALSE)
  UNION ALL
  SELECT 'FEWER_THAN_FIVE_REFERENCES', NULL, COUNT(*), NULL
  FROM SR_DB.TEST.FX_RECON_REFERENCE HAVING COUNT(*) < 5
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
