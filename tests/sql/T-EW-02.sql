-- T-EW-02 (SR-028, stretch): ML_CONFIRMED is true only, and always, where the lever model flagged the latest week
-- for that market, brand and signal.
SET TEST_ID = 'T-EW-02';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH flagged AS (
  SELECT DISTINCT MARKET_ID, BRAND, SIGNAL FROM SR_DB.ML.AD_LEVERS_RESULT WHERE RUN_ID = $RUN_UNDER_TEST AND FLAGGED
),
failures AS (
  SELECT e.MARKET_ID, e.BRAND, e.SIGNAL, e.ML_CONFIRMED, (f.BRAND IS NOT NULL) AS MODEL_FLAGGED
  FROM SR_DB.APP.EARLY_WARNING e
  LEFT JOIN flagged f ON f.MARKET_ID = e.MARKET_ID AND f.BRAND = e.BRAND AND f.SIGNAL = e.SIGNAL
  WHERE e.RUN_ID = $RUN_UNDER_TEST AND COALESCE(e.ML_CONFIRMED, FALSE) <> (f.BRAND IS NOT NULL)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
