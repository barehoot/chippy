-- T-WH-02 (SR-023): at most 5 TOP_INSIGHTS rows per shift; when that step logged WARN, the EXACT_RETAILER rows
-- still exist for parent-market selected shifts.
SET TEST_ID = 'T-WH-02';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH failures AS (
  SELECT 'MORE_THAN_5' AS PROBLEM, SHIFT_ID, COUNT(*) AS N
  FROM SR_DB.APP.SHIFT_WHERE WHERE RUN_ID = $RUN_UNDER_TEST AND METHOD = 'TOP_INSIGHTS'
  GROUP BY SHIFT_ID HAVING COUNT(*) > 5
  UNION ALL
  SELECT 'EXACT_MISSING_AFTER_WARN', r.SHIFT_ID, 0
  FROM SR_DB.APP.SHIFT_RANKED r
  WHERE r.RUN_ID = $RUN_UNDER_TEST AND r.SELECTED
    AND r.MARKET_ID = (SELECT SETTING_VALUE::VARCHAR FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'SCOPE_PARENT_MARKET')
    AND EXISTS (SELECT 1 FROM SR_DB.OPS.STEP_LOG s WHERE s.RUN_ID = r.RUN_ID AND s.STEP = 'TOP_INSIGHTS' AND s.STATUS = 'WARN')
    AND NOT EXISTS (SELECT 1 FROM SR_DB.APP.SHIFT_WHERE w
                    WHERE w.RUN_ID = r.RUN_ID AND w.SHIFT_ID = r.SHIFT_ID AND w.METHOD = 'EXACT_RETAILER')
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
