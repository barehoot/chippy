-- T-EW-01 (SR-027): PROJECTED_SHARE_PTS equals 100 x s(L4W) x (DS latest / DS L4W - 1) within 1e-9, recomputed
-- from the dynamic tables; only rows with LEVER_CHG <= EW_DIST_DROP are DIST_DROP.
SET TEST_ID = 'T-EW-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- l4: L4W value and distribution share straight from the period tables
WITH l4 AS (
  SELECT bp.MARKET_ID, bp.CATEGORY, bp.BRAND,
         SUM(bp.VALUE_SALES) / NULLIF(MAX(cp.CAT_VALUE_SALES), 0) AS S_L4W,
         SUM(bp.TDP_SUM)     / NULLIF(MAX(cp.CAT_TDP_SUM), 0)     AS DS_L4W
  FROM SR_DB.CORE.DT_BRAND_PERIOD bp
  JOIN SR_DB.CORE.DT_CAT_PERIOD cp ON cp.PERIOD_CODE = bp.PERIOD_CODE AND cp.MARKET_ID = bp.MARKET_ID AND cp.CATEGORY = bp.CATEGORY
  WHERE bp.PERIOD_CODE = 'L4W'
  GROUP BY bp.MARKET_ID, bp.CATEGORY, bp.BRAND
),
-- lw: latest-week distribution share from the weekly tables
lw AS (
  SELECT b.MARKET_ID, b.CATEGORY, b.BRAND, SUM(b.TDP) / NULLIF(MAX(c.TDP), 0) AS DS_LATEST
  FROM SR_DB.CORE.DT_BRAND_WEEK b
  JOIN SR_DB.CORE.DT_CAT_WEEK c ON c.WEEK_END_DATE = b.WEEK_END_DATE AND c.MARKET_ID = b.MARKET_ID AND c.CATEGORY = b.CATEGORY
  WHERE b.WEEK_END_DATE = (SELECT MAX(WEEK_END_DATE) FROM SR_DB.CORE.DT_BRAND_WEEK)
  GROUP BY b.MARKET_ID, b.CATEGORY, b.BRAND
),
failures AS (
  SELECT 'PROJECTION' AS PROBLEM, e.MARKET_ID, e.BRAND, e.PROJECTED_SHARE_PTS AS GOT,
         100 * l4.S_L4W * (lw.DS_LATEST / l4.DS_L4W - 1) AS WANT
  FROM SR_DB.APP.EARLY_WARNING e
  JOIN l4 ON l4.MARKET_ID = e.MARKET_ID AND l4.CATEGORY = e.CATEGORY AND l4.BRAND = e.BRAND
  JOIN lw ON lw.MARKET_ID = e.MARKET_ID AND lw.CATEGORY = e.CATEGORY AND lw.BRAND = e.BRAND
  WHERE e.RUN_ID = $RUN_UNDER_TEST AND e.SIGNAL = 'DIST_DROP'
    AND NOT (ABS(e.PROJECTED_SHARE_PTS - 100 * l4.S_L4W * (lw.DS_LATEST / l4.DS_L4W - 1)) <= 1e-9)
  UNION ALL
  SELECT 'ABOVE_THRESHOLD', MARKET_ID, BRAND, LEVER_CHG, (SELECT SETTING_VALUE::FLOAT FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'EW_DIST_DROP')
  FROM SR_DB.APP.EARLY_WARNING
  WHERE RUN_ID = $RUN_UNDER_TEST AND SIGNAL = 'DIST_DROP'
    AND NOT (LEVER_CHG <= (SELECT SETTING_VALUE::FLOAT FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'EW_DIST_DROP'))
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
