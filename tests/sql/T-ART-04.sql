-- T-ART-04 (SR-024): the label is POSSIBLE_DATA_EFFECT exactly when a HIGH rule matches the shift's market or
-- brand, MIXED when only MEDIUM rules match, and MARKET_MOVE otherwise.
SET TEST_ID = 'T-ART-04';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- sev: matching rule severities per ranked shift
WITH sev AS (
  SELECT r.SHIFT_ID, r.ARTEFACT_LABEL,
         COUNT_IF(a.SEVERITY = 'HIGH') AS N_HIGH, COUNT_IF(a.SEVERITY = 'MEDIUM') AS N_MED
  FROM SR_DB.APP.SHIFT_RANKED r
  LEFT JOIN SR_DB.APP.ARTEFACT_CHECK a
    ON a.RUN_ID = r.RUN_ID AND a.CMP_CODE = r.CMP_CODE AND a.MARKET_ID = r.MARKET_ID AND a.CATEGORY = r.CATEGORY
   AND (a.BRAND IS NULL OR a.BRAND = r.BRAND)
  WHERE r.RUN_ID = $RUN_UNDER_TEST
  GROUP BY r.SHIFT_ID, r.ARTEFACT_LABEL
),
failures AS (
  SELECT SHIFT_ID, ARTEFACT_LABEL, N_HIGH, N_MED FROM sev
  WHERE ARTEFACT_LABEL <> CASE WHEN N_HIGH > 0 THEN 'POSSIBLE_DATA_EFFECT' WHEN N_MED > 0 THEN 'MIXED' ELSE 'MARKET_MOVE' END
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
