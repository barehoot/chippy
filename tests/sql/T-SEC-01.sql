-- T-SEC-01 (SR-056): as SR_JUDGE with no secondary roles, writes, APP table reads and EXECUTE TASK all fail, and
-- reading the SEM views succeeds. The judge role cannot write the result, so the block returns the statements that
-- wrongly succeeded (or wrongly failed) and the test records them through RESULT_SCAN as SR_DEV.
SET TEST_ID = 'T-SEC-01';
USE ROLE SR_JUDGE;
USE SECONDARY ROLES NONE;
EXECUTE IMMEDIATE $$
DECLARE
  fails ARRAY DEFAULT ARRAY_CONSTRUCT();
  n     NUMBER;
BEGIN
  BEGIN
    INSERT INTO SR_DB.OPS.SETTINGS (SETTING_KEY, SETTING_VALUE) SELECT 'X', TO_VARIANT(1);
    fails := ARRAY_APPEND(fails, 'insert into OPS.SETTINGS succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    UPDATE SR_DB.APP.BRIEF SET HEADLINE = HEADLINE WHERE 1 = 0;
    fails := ARRAY_APPEND(fails, 'update of APP.BRIEF succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    EXECUTE TASK SR_DB.OPS.T_RUN_WEEK_MANUAL;
    fails := ARRAY_APPEND(fails, 'EXECUTE TASK succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    SELECT COUNT(*) INTO :n FROM SR_DB.APP.SHIFT_RANKED;
    fails := ARRAY_APPEND(fails, 'SELECT on APP.SHIFT_RANKED succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    SELECT COUNT(*) INTO :n FROM SR_DB.CORE.DT_SHARE_COMPARE;
    fails := ARRAY_APPEND(fails, 'SELECT on CORE.DT_SHARE_COMPARE succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    CALL SR_DB.APP.SP_RUN_WEEK('MANUAL', TRUE);
    fails := ARRAY_APPEND(fails, 'CALL SP_RUN_WEEK succeeded');
  EXCEPTION WHEN OTHER THEN NULL;
  END;
  BEGIN
    SELECT COUNT(*) INTO :n FROM SR_DB.SEM.V_SEM_SHARE_CHANGE;
  EXCEPTION WHEN OTHER THEN
    fails := ARRAY_APPEND(fails, 'SELECT on SEM.V_SEM_SHARE_CHANGE failed: ' || LEFT(SQLERRM, 120));
  END;
  BEGIN
    SELECT COUNT(*) INTO :n FROM SR_DB.SEM.V_TOOL_BRIDGE;
  EXCEPTION WHEN OTHER THEN
    fails := ARRAY_APPEND(fails, 'SELECT on SEM.V_TOOL_BRIDGE failed: ' || LEFT(SQLERRM, 120));
  END;
  RETURN ARRAY_TO_STRING(fails, '; ');
END;
$$;
SET Q = LAST_QUERY_ID();
USE ROLE SR_DEV;
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
SELECT $TEST_RUN_ID, $TEST_ID, $1 = '', IFF($1 = '', 0, ARRAY_SIZE(SPLIT($1, '; '))), TO_VARIANT($1)
FROM TABLE(RESULT_SCAN($Q));
