-- T-SRC-01 (SR-003): every L3 contract column exists in the adapter views, with the contract type family.
SET TEST_ID = 'T-SRC-01';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- expected: the L3 contract, as (view, column, type family)
WITH expected AS (
  SELECT column1 AS TABLE_NAME, column2 AS COLUMN_NAME, column3 AS FAMILY
  FROM VALUES
    ('V_SRC_FACT_WEEKLY_ALL', 'WEEK_END_DATE', 'DATE'), ('V_SRC_FACT_WEEKLY_ALL', 'MARKET_ID', 'TEXT'),
    ('V_SRC_FACT_WEEKLY_ALL', 'PRODUCT_ID', 'TEXT'),    ('V_SRC_FACT_WEEKLY_ALL', 'VALUE_SALES', 'NUMBER'),
    ('V_SRC_FACT_WEEKLY_ALL', 'VOLUME_SALES', 'NUMBER'),('V_SRC_FACT_WEEKLY_ALL', 'UNIT_SALES', 'NUMBER'),
    ('V_SRC_FACT_WEEKLY_ALL', 'ACV_DIST_PCT', 'NUMBER'),('V_SRC_FACT_WEEKLY_ALL', 'BASE_VALUE_SALES', 'NUMBER'),
    ('V_SRC_FACT_WEEKLY_ALL', 'BASE_UNIT_SALES', 'NUMBER'), ('V_SRC_FACT_WEEKLY_ALL', 'STORES_SELLING', 'NUMBER'),
    ('V_SRC_FACT_WEEKLY_ALL', 'DATA_VERSION', 'TEXT'),
    ('V_SRC_PRODUCT', 'PRODUCT_ID', 'TEXT'), ('V_SRC_PRODUCT', 'ITEM_DESC', 'TEXT'), ('V_SRC_PRODUCT', 'BRAND', 'TEXT'),
    ('V_SRC_PRODUCT', 'MANUFACTURER', 'TEXT'), ('V_SRC_PRODUCT', 'CATEGORY', 'TEXT'), ('V_SRC_PRODUCT', 'SEGMENT', 'TEXT'),
    ('V_SRC_PRODUCT', 'PACK_SIZE', 'TEXT'), ('V_SRC_PRODUCT', 'IS_PRIVATE_LABEL', 'BOOLEAN'),
    ('V_SRC_MARKET', 'MARKET_ID', 'TEXT'), ('V_SRC_MARKET', 'MARKET_NAME', 'TEXT'), ('V_SRC_MARKET', 'MARKET_LEVEL', 'TEXT'),
    ('V_SRC_MARKET', 'PARENT_MARKET_ID', 'TEXT'), ('V_SRC_MARKET', 'RETAILER', 'TEXT'), ('V_SRC_MARKET', 'CHANNEL', 'TEXT'),
    ('V_SRC_MARKET', 'REGION', 'TEXT')
),
-- actual: column types from the information schema, folded to the same families
actual AS (
  SELECT TABLE_NAME, COLUMN_NAME,
         CASE WHEN DATA_TYPE IN ('NUMBER', 'FLOAT') THEN 'NUMBER' ELSE DATA_TYPE END AS FAMILY
  FROM SR_DB.INFORMATION_SCHEMA.COLUMNS
  WHERE TABLE_SCHEMA = 'SRC'
),
failures AS (
  SELECT e.TABLE_NAME, e.COLUMN_NAME, e.FAMILY AS EXPECTED_FAMILY, a.FAMILY AS ACTUAL_FAMILY
  FROM expected e
  LEFT JOIN actual a ON a.TABLE_NAME = e.TABLE_NAME AND a.COLUMN_NAME = e.COLUMN_NAME
  WHERE a.FAMILY IS NULL OR a.FAMILY <> e.FAMILY
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
