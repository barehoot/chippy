-- T-NAR-04 (SR-032, E2E): with LLM_MODEL and LLM_FALLBACK_MODEL set to a model that does not exist,
-- SP_WRITE_BRIEF still publishes, with GENERATOR = 'TEMPLATE' and a template that passed the validator (the last
-- VIOLATIONS entry is the template's check, and it is empty). Settings are restored even if the test fails.
SET TEST_ID = 'T-NAR-04';
EXECUTE IMMEDIATE $$
DECLARE
  fails ARRAY DEFAULT ARRAY_CONSTRUCT();
  m1    VARIANT;
  m2    VARIANT;
  rid   VARCHAR;
  bid   VARCHAR;
  gen   VARCHAR;
  last  VARIANT;
BEGIN
  IF (NOT $RUN_E2E) THEN RETURN 'SKIPPED_NO_E2E'; END IF;
  SELECT RUN_ID INTO :rid FROM SR_DB.APP.FACT_PACK ORDER BY CREATED_AT DESC LIMIT 1;
  SELECT SETTING_VALUE INTO :m1 FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'LLM_MODEL';
  SELECT SETTING_VALUE INTO :m2 FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'LLM_FALLBACK_MODEL';
  UPDATE SR_DB.OPS.SETTINGS SET SETTING_VALUE = TO_VARIANT('no-such-model-sr')
   WHERE SETTING_KEY IN ('LLM_MODEL', 'LLM_FALLBACK_MODEL');
  BEGIN
    CALL SR_DB.APP.SP_WRITE_BRIEF(:rid) INTO :bid;
  EXCEPTION
    WHEN OTHER THEN
      fails := ARRAY_APPEND(fails, 'SP_WRITE_BRIEF raised: ' || LEFT(SQLERRM, 200));
  END;
  UPDATE SR_DB.OPS.SETTINGS SET SETTING_VALUE = :m1 WHERE SETTING_KEY = 'LLM_MODEL';
  UPDATE SR_DB.OPS.SETTINGS SET SETTING_VALUE = :m2 WHERE SETTING_KEY = 'LLM_FALLBACK_MODEL';
  IF (bid IS NOT NULL) THEN
    SELECT GENERATOR, VIOLATIONS[ARRAY_SIZE(VIOLATIONS) - 1] INTO :gen, :last
      FROM SR_DB.APP.BRIEF WHERE BRIEF_ID = :bid AND STATUS = 'PUBLISHED';
    IF (gen IS NULL OR gen <> 'TEMPLATE') THEN fails := ARRAY_APPEND(fails, 'generator ' || COALESCE(gen, 'none')); END IF;
    IF (GET(last, 'attempt')::VARCHAR <> 'template' OR ARRAY_SIZE(GET(last, 'violations')) <> 0) THEN
      fails := ARRAY_APPEND(fails, 'template check ' || TO_JSON(last));
    END IF;
  END IF;
  RETURN ARRAY_TO_STRING(fails, '; ');
END;
$$;
SET Q = LAST_QUERY_ID();
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
SELECT $TEST_RUN_ID, $TEST_ID, $1 = '', IFF($1 = '', 0, ARRAY_SIZE(SPLIT($1, '; '))), TO_VARIANT($1)
FROM TABLE(RESULT_SCAN($Q)) WHERE $1 <> 'SKIPPED_NO_E2E';
