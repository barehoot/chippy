-- T-SEC-03 (SR-056): RAP_ENTITLED is attached to all seven SEM views (it is dropped by any CREATE OR REPLACE VIEW,
-- so this test runs after every change in sql/50_sem and 702 has been rerun).
SET TEST_ID = 'T-SEC-03';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
WITH expected AS (
  SELECT column1 AS VIEW_NAME FROM VALUES ('V_SEM_SHARE_GRID'), ('V_SEM_SHARE_CHANGE'), ('V_TOOL_BRIDGE'),
                                          ('V_TOOL_WHERE'), ('V_TOOL_ARTEFACT'), ('V_TOOL_FLOW'), ('V_TOOL_BRIEF')
),
attached AS (
  SELECT REF_ENTITY_NAME AS VIEW_NAME
  FROM TABLE(SR_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(POLICY_NAME => 'SR_DB.OPS.RAP_ENTITLED'))
  WHERE REF_SCHEMA_NAME = 'SEM' AND POLICY_STATUS = 'ACTIVE'
),
failures AS (
  SELECT e.VIEW_NAME FROM expected e WHERE e.VIEW_NAME NOT IN (SELECT VIEW_NAME FROM attached)
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
