-- T-CORE-02 (SR-011): per week and market, brand value sales sum to the adapter's scope-category sales within 0.01.
SET TEST_ID = 'T-CORE-02';
INSERT INTO SR_DB.OPS.TEST_RESULT (TEST_RUN_ID, TEST_ID, PASSED, FAILURES, DETAIL)
-- src: category sales recomputed straight from the adapter
WITH src AS (
  SELECT f.WEEK_END_DATE, f.MARKET_ID, SUM(f.VALUE_SALES) AS V
  FROM SR_DB.SRC.V_SRC_FACT_WEEKLY f
  JOIN SR_DB.SRC.V_SRC_PRODUCT p ON p.PRODUCT_ID = f.PRODUCT_ID
  WHERE p.CATEGORY = SR_DB.OPS.CFG('SCOPE_CATEGORY')::VARCHAR
  GROUP BY f.WEEK_END_DATE, f.MARKET_ID
),
-- dt: the same total from the brand-week table
dt AS (
  SELECT WEEK_END_DATE, MARKET_ID, SUM(VALUE_SALES) AS V
  FROM SR_DB.CORE.DT_BRAND_WEEK GROUP BY WEEK_END_DATE, MARKET_ID
),
failures AS (
  SELECT COALESCE(s.WEEK_END_DATE, d.WEEK_END_DATE) AS WEEK_END_DATE, COALESCE(s.MARKET_ID, d.MARKET_ID) AS MARKET_ID,
         s.V AS SRC_V, d.V AS DT_V
  FROM src s FULL OUTER JOIN dt d ON d.WEEK_END_DATE = s.WEEK_END_DATE AND d.MARKET_ID = s.MARKET_ID
  WHERE s.V IS NULL OR d.V IS NULL OR ABS(s.V - d.V) > 0.01
)
SELECT $TEST_RUN_ID, $TEST_ID, COUNT(*) = 0, COUNT(*),
       (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) FROM (SELECT * FROM failures LIMIT 20))
FROM failures;
